"""
Additional analyses requested in expert review (uses only saved predictions and the cohort).

  * reference models on the same folds: clinical logistic model, and clinical model + expert acute lesion volume
    (log volume and a mask indicator); late fusion of the clinical variables with the image-only networks (logit of the
    network's out-of-fold patient probability, in-fold logistic model; mildly optimistic because the training
    patients' network probabilities come from models that saw part of the test fold)
  * calibration (slope, intercept, Brier score) of every configuration
  * equivalence with the clinical model: 90% bootstrap CI of the paired AUC difference inside +/- MARGIN (two one-sided
    tests at 5%), and Holm-adjusted two-sided bootstrap p values over the 27 network configurations
  * within-patient agreement of slice probabilities (one-way intraclass correlation), which explains why slice-level
    and patient-level AUC are close
  * Grad-CAM: patient-clustered bootstrap CIs, maps that were empty, results by lesion-size quartile and, when present,
    the energy in the mirror-image control region
  * training variability: per-seed AUCs and the seed ensemble, for configurations with more than one seed
Outputs (results/thesis/paper): extra_reference.csv, extra_calibration.csv, extra_equivalence.csv, extra_icc.csv,
extra_gradcam.csv, extra_seeds.csv, numbers_t2.tex (macros \\NTT{key})
Usage: python src/thesis_extra.py   (run before thesis_eval.py, which draws the lesion-volume reference)
"""
import numpy as np, pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from common import RES, WORK, auc, clinical_matrix, calibration
from thesis_models import splits

MARGIN, B = 0.03, 2000
T = RES / "thesis"; OUT = T / "paper"; OUT.mkdir(parents=True, exist_ok=True)
coh = pd.read_csv(RES / "cohort_all.csv").set_index("participant_id")
L = coh[coh.labelled].copy()
L["log_vol"] = np.log1p(L.acute_ml_filled.fillna(0)); L["mask_ind"] = L.has_mask.astype(float)
y_all = L.y_poor.astype(int)
Ld = L.reset_index()


def patient_prob(tag):
    f = T / "oof" / f"{tag}.csv"
    if not f.exists():
        return None
    d = pd.read_csv(f)
    return d.groupby("participant_id").p.mean()


def fit_predict(split, extra_cols=(), extra_series=None):
    """In-fold logistic model of the clinical variables (+ optional columns or an external score) on the same splits."""
    p = pd.Series(np.nan, index=Ld.participant_id)
    for unit, tr, va, te in splits(Ld, split):
        fit = Ld[Ld.participant_id.isin(tr | va)]; tst = Ld[Ld.participant_id.isin(te)]
        Xf, Xt = clinical_matrix(fit, fit), clinical_matrix(tst, fit)
        if extra_cols:
            Xf = np.column_stack([Xf, fit[list(extra_cols)].values]); Xt = np.column_stack([Xt, tst[list(extra_cols)].values])
        if extra_series is not None:
            s = np.log(np.clip(extra_series, 1e-4, 1 - 1e-4) / (1 - np.clip(extra_series, 1e-4, 1 - 1e-4)))
            Xf = np.column_stack([Xf, s.reindex(fit.participant_id).values]); Xt = np.column_stack([Xt, s.reindex(tst.participant_id).values])
        sc = StandardScaler().fit(Xf)
        m = LogisticRegression(max_iter=2000).fit(sc.transform(Xf), fit.y_poor.astype(int))
        p[tst.participant_id] = m.predict_proba(sc.transform(Xt))[:, 1]
    return p.dropna()


def boot_pair(y, a, b, seed=0):
    """Paired bootstrap of AUC(a) - AUC(b): estimate, 95% CI, 90% CI, two-sided p."""
    rng = np.random.default_rng(seed); n = len(y); d = []
    for _ in range(B):
        i = rng.integers(0, n, n)
        if y[i].min() == y[i].max():
            continue
        d.append(auc(y[i], a[i]) - auc(y[i], b[i]))
    d = np.array(d); est = auc(y, a) - auc(y, b)
    p = min(1.0, 2 * min((d <= 0).mean(), (d >= 0).mean()))
    return est, np.percentile(d, [2.5, 97.5]), np.percentile(d, [5, 95]), p


def boot_auc(y, p, seed=0):
    rng = np.random.default_rng(seed); n = len(y); a = []
    for _ in range(B):
        i = rng.integers(0, n, n)
        if y[i].min() != y[i].max():
            a.append(auc(y[i], p[i]))
    return np.percentile(a, [2.5, 97.5])


mac = ["% generated by src/thesis_extra.py",
       "\\providecommand{\\NTT}[1]{\\ifcsname ntt@#1\\endcsname\\csname ntt@#1\\endcsname\\else\\textbf{\\textcolor{red}{??}}\\fi}"]
tex = lambda s: "$-$" + s[1:] if s.startswith("-") else s
put = lambda k, v, f="{:.3f}": mac.append(f"\\expandafter\\def\\csname ntt@{k}\\endcsname{{{tex(f.format(v))}}}") if v == v else None
key = lambda tag: tag.replace("__s0", "").replace("_", "").replace("-", "")

nets = sorted({f.stem.rsplit("__s", 1)[0] for f in (T / "oof").glob("*__s0.csv")})
ref = {s: fit_predict(s) for s in ["thesis", "cv5"]}
lesion = {s: fit_predict(s, ("log_vol", "mask_ind")) for s in ["thesis", "cv5"]}

# ------------------------------------------------------------------ reference models and late fusion
rows = []
for s in ["thesis", "cv5"]:
    for name, p in [("clinical", ref[s]), ("clinical_lesion", lesion[s])]:
        y = y_all.reindex(p.index).values; lo, hi = boot_auc(y, p.values)
        r = dict(model=name, split=s, n=len(p), auc=auc(y, p.values), lo=lo, hi=hi)
        if name != "clinical":
            est, ci, _, pv = boot_pair(y, p.values, ref[s].reindex(p.index).values)
            r.update(d_clin=est, d_lo=ci[0], d_hi=ci[1], p=pv)
        rows.append(r)
for arch in ["basic", "vgg16", "effb0"]:
    for inp in ["flair_axial", "t1_axial", "dwi_axial"]:
        img = patient_prob(f"{arch}__{inp}__none__cv5__s0")
        if img is None:
            continue
        p = fit_predict("cv5", extra_series=img)
        y = y_all.reindex(p.index).values; lo, hi = boot_auc(y, p.values)
        est, ci, _, pv = boot_pair(y, p.values, ref["cv5"].reindex(p.index).values)
        r = dict(model=f"latefusion_{arch}_{inp}", split="cv5", n=len(p), auc=auc(y, p.values), lo=lo, hi=hi,
                 d_clin=est, d_lo=ci[0], d_hi=ci[1], p=pv)
        e2, c2, _, p2 = boot_pair(y, p.values, lesion["cv5"].reindex(p.index).values)
        r.update(d_lesion=e2, dl_lo=c2[0], dl_hi=c2[1], p_lesion=p2); rows.append(r)
# networks with clinical variables against the lesion model
for arch in ["basic", "vgg16", "effb0"]:
    pn = patient_prob(f"{arch}__dwi_axial__fold__cv5__s0")
    if pn is None:
        continue
    y = y_all.reindex(pn.index).values
    est, ci, _, pv = boot_pair(y, pn.values, lesion["cv5"].reindex(pn.index).values)
    rows.append(dict(model=f"network_{arch}_dwi_vs_lesion", split="cv5", n=len(pn), auc=auc(y, pn.values),
                     d_lesion=est, dl_lo=ci[0], dl_hi=ci[1], p_lesion=pv))
REF = pd.DataFrame(rows); REF.round(4).to_csv(OUT / "extra_reference.csv", index=False)
for _, r in REF.iterrows():
    k = r.model.replace("_", "") + r.split
    for c in ["auc", "lo", "hi", "d_clin", "d_lo", "d_hi", "p", "d_lesion", "dl_lo", "dl_hi", "p_lesion"]:
        if c in r and pd.notna(r[c]):
            put(k + c.replace("_", ""), float(r[c]))

# ------------------------------------------------------------------ calibration, equivalence and Holm
cal, eq = [], []
for tag in nets + ["clinical__thesis", "clinical__cv5"]:
    if tag.startswith("clinical"):
        p = ref[tag.split("__")[1]]
    else:
        p = patient_prob(tag + "__s0")
    if p is None:
        continue
    y = y_all.reindex(p.index).values
    a_, b_ = calibration(y, p.values)
    cal.append(dict(tag=tag, cal_intercept=a_, cal_slope=b_, brier=float(np.mean((p.values - y) ** 2))))
    if not tag.startswith("clinical"):
        split = tag.split("__")[3]
        est, ci, ci90, pv = boot_pair(y, p.values, ref[split].reindex(p.index).values)
        eq.append(dict(tag=tag, d=est, lo95=ci[0], hi95=ci[1], lo90=ci90[0], hi90=ci90[1], p=pv,
                       equivalent=bool(ci90[0] > -MARGIN and ci90[1] < MARGIN), superior=bool(ci[0] > 0), inferior=bool(ci[1] < 0)))
CAL = pd.DataFrame(cal); CAL.round(4).to_csv(OUT / "extra_calibration.csv", index=False)
EQ = pd.DataFrame(eq)
if len(EQ):
    order = np.argsort(EQ.p.values); m = len(EQ); adj = np.empty(m); run = 0.0
    for rank, i in enumerate(order):                      # Holm step-down
        run = max(run, min(1.0, (m - rank) * EQ.p.values[i])); adj[i] = run
    EQ["p_holm"] = adj; EQ["superior_holm"] = (EQ.p_holm < 0.05) & (EQ.d > 0)
EQ.round(4).to_csv(OUT / "extra_equivalence.csv", index=False)
for _, r in CAL.iterrows():
    k = "clin" + r.tag.split("__")[1] if r.tag.startswith("clinical") else key(r.tag)
    put(k + "calslope", r.cal_slope, "{:.2f}"); put(k + "calint", r.cal_intercept, "{:.2f}"); put(k + "brier", r.brier)
for _, r in EQ.iterrows():
    k = key(r.tag)
    put(k + "lonine", r.lo90); put(k + "hinine", r.hi90); put(k + "pholm", r.p_holm, "{:.3f}" if r.p_holm >= 0.001 else "{:.4f}")
put("margin", MARGIN, "{:.2f}"); put("neq", len(EQ), "{:.0f}")
put("nequiv", int(EQ.equivalent.sum()) if len(EQ) else np.nan, "{:.0f}")
put("nsupholm", int(EQ.superior_holm.sum()) if len(EQ) else np.nan, "{:.0f}")

# ------------------------------------------------------------------ within-patient agreement of slice probabilities
icc = []
for tag in nets:
    f = T / "oof" / f"{tag}__s0.csv"
    if not f.exists():
        continue
    d = pd.read_csv(f); g = d.groupby("participant_id").p
    k_ = g.size().mean(); msb = k_ * g.mean().var(ddof=1); msw = g.var(ddof=1).mean()
    icc.append(dict(tag=tag, icc=(msb - msw) / (msb + (k_ - 1) * msw)))
ICC = pd.DataFrame(icc); ICC.round(4).to_csv(OUT / "extra_icc.csv", index=False)
for _, r in ICC.iterrows():
    put(key(r.tag) + "icc", r.icc, "{:.2f}")
for grp, sel in [("clinfold", ICC.tag.str.contains("__fold__|__thesis__")), ("none", ICC.tag.str.contains("__none__"))]:
    for arch in ["basic", "pre"]:
        s = ICC[sel & (ICC.tag.str.startswith("basic") if arch == "basic" else ~ICC.tag.str.startswith("basic"))]
        if len(s):
            put(f"icc{arch}{grp}min", s.icc.min(), "{:.2f}"); put(f"icc{arch}{grp}max", s.icc.max(), "{:.2f}")

# ------------------------------------------------------------------ Grad-CAM with patient-clustered CIs
gr = []
for f in sorted(T.glob("gradcam_*__s0.csv")):
    g = pd.read_csv(f); tag = f.stem.replace("gradcam_", "")
    if "cam_empty" not in g:
        g["cam_empty"] = 0
    ok = g[g.cam_empty == 0].dropna(subset=["energy_in_lesion"])
    P = ok.groupby("participant_id").agg(e=("energy_in_lesion", "mean"), a=("lesion_area_frac", "mean"))
    rng = np.random.default_rng(0); ids = P.index.values; bs = []
    for _ in range(B):
        s = P.loc[rng.choice(ids, len(ids))]
        bs.append((s.e.mean() - s.a.mean(), s.e.mean() / s.a.mean()))
    bs = np.array(bs)
    r = dict(tag=tag, slices=len(g), empty=int(g.cam_empty.sum()), patients=len(P), energy=P.e.mean(),
             area=P.a.mean(), ratio=P.e.mean() / P.a.mean(),
             ratio_lo=np.percentile(bs[:, 1], 2.5), ratio_hi=np.percentile(bs[:, 1], 97.5),
             excess=P.e.mean() - P.a.mean(), excess_lo=np.percentile(bs[:, 0], 2.5), excess_hi=np.percentile(bs[:, 0], 97.5))
    q = pd.qcut(ok.lesion_px, 4, labels=False)
    for i in range(4):
        s = ok[q == i].groupby("participant_id")[["energy_in_lesion", "lesion_area_frac"]].mean()
        r[f"ratio_q{i + 1}"] = s.energy_in_lesion.mean() / s.lesion_area_frac.mean()
    if "energy_in_mirror" in ok:
        Pm = ok.groupby("participant_id")[["energy_in_mirror", "mirror_area_frac"]].mean()
        r["mirror_energy"] = Pm.energy_in_mirror.mean(); r["mirror_area"] = Pm.mirror_area_frac.mean()
        r["ratio_mirror"] = r["mirror_energy"] / r["mirror_area"]
    gr.append(r)
GR = pd.DataFrame(gr); GR.round(4).to_csv(OUT / "extra_gradcam.csv", index=False)
for _, r in GR.iterrows():
    k = "gc" + r.tag.split("__")[0] + r.tag.split("__")[2]
    for c in ["ratio", "ratio_lo", "ratio_hi", "ratio_q1", "ratio_q4", "ratio_mirror", "mirror_energy"]:
        if c in r and pd.notna(r[c]):
            put(k + c.replace("_", ""), float(r[c]), "{:.2f}" if c.startswith("ratio") else "{:.3f}")
    put(k + "energy", r.energy); put(k + "area", r.area)
    put(k + "empty", r["empty"], "{:.0f}"); put(k + "patients", r.patients, "{:.0f}")

# ------------------------------------------------------------------ training variability over seeds
sd = []
for tag in nets:
    fs = sorted((T / "oof").glob(f"{tag}__s*.csv"))
    if len(fs) < 2:
        continue
    per = []
    for f in fs:
        p = pd.read_csv(f).groupby("participant_id").p.mean(); per.append(auc(y_all.reindex(p.index).values, p.values))
    ens = pd.concat([pd.read_csv(f) for f in fs]).groupby(["participant_id", "unit", "src", "slice"]).p.mean() \
        .groupby("participant_id").mean()
    sd.append(dict(tag=tag, n_seeds=len(fs), auc_s0=per[0], auc_mean=np.mean(per), auc_sd=np.std(per, ddof=1),
                   auc_min=min(per), auc_max=max(per), auc_ensemble=auc(y_all.reindex(ens.index).values, ens.values)))
SD = pd.DataFrame(sd); SD.round(4).to_csv(OUT / "extra_seeds.csv", index=False)
for _, r in SD.iterrows():
    k = key(r.tag)
    for c in ["auc_mean", "auc_sd", "auc_min", "auc_max", "auc_ensemble"]:
        put(k + "seed" + c.replace("_", "").replace("auc", ""), r[c])
    put(k + "nseeds", r.n_seeds, "{:.0f}")
if len(SD):
    put("seedsdmax", SD.auc_sd.max()); put("seedsdmed", SD.auc_sd.median())

# ------------------------------------------------------------------ cohort flow and included versus excluded
c = coh.reset_index()
put("nsessions", len(c), "{:.0f}"); put("nmrs", c.mrs.notna().sum(), "{:.0f}")
put("nmrsnoage", (c.mrs.notna() & c.age.isna()).sum(), "{:.0f}")
E = c[~c.labelled & c.dwi_ok]
for nm, d in [("incl", L), ("excl", E)]:
    put(nm + "n", len(d), "{:.0f}"); put(nm + "nihss", d.nihss.median(), "{:.0f}"); put(nm + "nnihss", d.nihss.notna().sum(), "{:.0f}")
    put(nm + "age", d.age.median(), "{:.0f}"); put(nm + "vol", d.acute_ml.median(), "{:.1f}")
put("ndeaths", (L.mrs == 6).sum(), "{:.0f}"); put("nbmimiss", L.bmi.isna().sum(), "{:.0f}")
put("poorbmimiss", 100 * L[L.bmi.isna()].y_poor.mean(), "{:.0f}"); put("poorbmiobs", 100 * L[L.bmi.notna()].y_poor.mean(), "{:.0f}")
m = L[L.has_mask.astype(bool)]
put("priorchronicyes", int(((m.priorstroke == 1) & (m.chronic_ml_filled.fillna(0) >= 1)).sum()), "{:.0f}")
put("prioryes", int((m.priorstroke == 1).sum()), "{:.0f}")
put("priornochronic", int(((m.priorstroke == 0) & (m.chronic_ml_filled.fillna(0) >= 1)).sum()), "{:.0f}")
put("priorno", int((m.priorstroke == 0).sum()), "{:.0f}")
put("poornomask", 100 * L[~L.has_mask.astype(bool)].y_poor.mean(), "{:.0f}"); put("poormask", 100 * m.y_poor.mean(), "{:.0f}")
(OUT / "numbers_t2.tex").write_text("\n".join(x for x in mac if x) + "\n")
print(REF.round(3).to_string()); print(CAL.round(3).to_string()); print(EQ.round(3).to_string())
print(ICC.round(3).to_string()); print(GR.round(3).to_string()); print(SD.round(3).to_string())
print("written", OUT / "numbers_t2.tex")
