"""
Bayesian analysis of practical equivalence between each network and the clinical model, and an exact interval for the
share of favorable random splits.

  * Posterior distribution of the paired difference in patient-level AUC (network minus the clinical logistic model on
    the same split) from the Bayesian bootstrap (Rubin, 1981): 4,000 Dirichlet(1, ..., 1) weight vectors over patients,
    shared by both models so that the pairing is kept. For the same 37 comparisons as the equivalence tests of
    thesis_extra.py, we report the posterior probabilities that the difference lies below, within or above a region of
    practical equivalence (ROPE). The primary margin is the one of the equivalence tests (+/-0.03); +/-0.02 is a
    sensitivity analysis (Kruschke, 2018; Benavoli et al., 2017).
  * The share of random 15% test splits on which the clinical model reached at least its AUC on the thesis split, with an
    exact (Clopper-Pearson) 95% interval.
Inputs: results/thesis/paper/patient_predictions.csv, extra_equivalence.csv, split_variability.csv, all_runs.csv
Outputs (results/thesis/paper): extra_bayes.csv, numbers_t3.tex (macros \\NTX{key}{field})
Usage: python src/thesis_bayes.py   (after thesis_eval.py and thesis_extra.py)
"""
import numpy as np, pandas as pd
from scipy.stats import beta
from common import RES

NDRAW, SEED, ROPE, ROPES = 4000, 20261118, 0.03, (0.02, 0.03)
OUT = RES / "thesis" / "paper"
PP = pd.read_csv(OUT / "patient_predictions.csv").set_index("participant_id")
EQ = pd.read_csv(OUT / "extra_equivalence.csv")


def weighted_auc(score, y, W):
    """AUC under each row of patient weights W (ties count one half)."""
    o = np.argsort(score, kind="mergesort"); s, yy, Ww = score[o], y[o], W[:, o]
    neg, pos = Ww * (yy == 0), Ww * (yy == 1)
    _, start, cnt = np.unique(s, return_index=True, return_counts=True)
    gneg = np.add.reduceat(neg, start, axis=1)
    prev = np.concatenate([np.zeros((W.shape[0], 1)), np.cumsum(gneg, axis=1)[:, :-1]], axis=1)
    gid = np.repeat(np.arange(len(start)), cnt)
    below = prev[:, gid] + 0.5 * gneg[:, gid]
    return (pos * below).sum(1) / (pos.sum(1) * neg.sum(1))


rng = np.random.default_rng(SEED)
rows, Wcache = [], {}
for tag in EQ.tag:
    split = tag.split("__")[3]
    d = PP[["y_poor", tag, f"clinical__{split}"]].dropna()
    y = d.y_poor.values.astype(int); n = len(y)
    if n not in Wcache:
        Wcache[n] = rng.dirichlet(np.ones(n), size=NDRAW)
    W = Wcache[n]
    delta = weighted_auc(d[tag].values, y, W) - weighted_auc(d[f"clinical__{split}"].values, y, W)
    r = dict(tag=tag, n=n, d_mean=delta.mean(), d_lo=np.quantile(delta, .025), d_hi=np.quantile(delta, .975),
             p_gt0=(delta > 0).mean())
    for m in ROPES:
        r[f"p_worse_{m}"], r[f"p_rope_{m}"], r[f"p_better_{m}"] = (delta < -m).mean(), (np.abs(delta) <= m).mean(), (delta > m).mean()
    rows.append(r)
BX = pd.DataFrame(rows); BX.round(4).to_csv(OUT / "extra_bayes.csv", index=False)

R = pd.read_csv(OUT / "all_runs.csv")
clin_thesis = R.loc[R.tag == "clinical__thesis", "auc_patient"].item()
SV = pd.read_csv(OUT / "split_variability.csv").auc.values
k, nsv = int((SV >= clin_thesis - 1e-9).sum()), len(SV)
cp = (beta.ppf(0.025, k, nsv - k + 1) if k > 0 else 0.0, beta.ppf(0.975, k + 1, nsv - k) if k < nsv else 1.0)


def key(tag):
    return tag.replace("__", "").replace("_", "")


cv = BX[BX.tag.str.endswith("cv5")]
flt1 = cv[cv.tag.str.contains("flair|t1|mix") & cv.tag.str.contains("__fold__|__thesis__|__thesisprep__")]
with open(OUT / "numbers_t3.tex", "w") as f:
    f.write("% generated by src/thesis_bayes.py\n\\providecommand{\\NTX}[2]{\\csname ntx@#1@#2\\endcsname}\n")

    def w(a, b, v, fmt="{:.2f}"):
        f.write("\\expandafter\\def\\csname ntx@%s@%s\\endcsname{%s}\n" % (a, b, fmt.format(v).replace("-", "$-$")))
    for _, r in BX.iterrows():
        kk = key(r.tag)
        w(kk, "prope", r[f"p_rope_{ROPE}"]); w(kk, "propetwo", r["p_rope_0.02"])
        w(kk, "pbetter", r[f"p_better_{ROPE}"]); w(kk, "pbettertwo", r["p_better_0.02"])
        w(kk, "pworse", r[f"p_worse_{ROPE}"]); w(kk, "pgtzero", r.p_gt0)
    # summaries over the FLAIR / T1w / FLAIR + T1w networks with clinical variables in cross-validation
    w("sum", "nflt", len(flt1), "{:d}")
    w("sum", "fltpropemin", flt1[f"p_rope_{ROPE}"].min()); w("sum", "fltpropetwomin", flt1["p_rope_0.02"].min())
    w("sum", "fltnpropetwoge", int((flt1["p_rope_0.02"] >= 0.95).sum()), "{:d}")
    bv = flt1[flt1.tag.str.startswith(("basic", "vgg16"))]
    w("sum", "bvpropemin", bv[f"p_rope_{ROPE}"].min()); w("sum", "bvpropetwomin", bv["p_rope_0.02"].min())
    eqcv = EQ[EQ.tag.isin(flt1.tag)]
    w("sum", "nfltcveq", int(eqcv.equivalent.sum()), "{:d}")
    w("sum", "neqthesis", int(EQ[EQ.tag.str.endswith("thesis") & EQ.equivalent].shape[0]), "{:d}")
    w("sv", "k", k, "{:d}"); w("sv", "n", nsv, "{:d}"); w("sv", "pct", 100 * k / nsv, "{:.0f}")
    w("sv", "cplo", 100 * cp[0], "{:.1f}"); w("sv", "cphi", 100 * cp[1], "{:.1f}")
print(BX.round(3).to_string())
print("favorable splits", k, nsv, cp)
print(flt1[["tag", "p_rope_0.03", "p_rope_0.02", "p_gt0"]].round(3).to_string())
